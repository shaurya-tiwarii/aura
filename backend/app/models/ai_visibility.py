"""AI-search readiness report and category scores (Module 7).

Mirrors the SEO report structure, but scores a different question: how well is
this site's content structured for an AI system that needs to extract, quote, and
attribute an answer?

Honesty constraint (spec sections 7 and 45)
-------------------------------------------
This score is a **heuristic over observable content and structural signals**.
It cannot and does not measure actual behaviour of ChatGPT, Gemini, Perplexity,
or Google. ``disclaimer`` carries that statement on every report row so the
caveat travels with the data into the API and the UI, rather than living only in
frontend copy that could drift.
"""

from __future__ import annotations

import uuid
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, JSONColumn, TimestampMixin, UUIDPrimaryKeyMixin
from app.models.enums import ScoreGrade

if TYPE_CHECKING:
    from app.models.website import WebsiteScan

HEURISTIC_DISCLAIMER = (
    "The AI Visibility Score is an estimate of AI-search readiness, calculated "
    "from content and structural signals on your website. It is a heuristic: it "
    "does not measure or guarantee how any AI system ranks, cites, or recommends "
    "your site."
)


class AiVisibilityReport(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Headline AI-visibility result for one scan."""

    __tablename__ = "ai_visibility_reports"

    scan_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("website_scans.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )

    overall_score: Mapped[float] = mapped_column(Float, nullable=False)
    grade: Mapped[str] = mapped_column(String(16), nullable=False)

    points_earned: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    points_available: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    pages_analyzed: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    engine_version: Mapped[str] = mapped_column(
        String(20), nullable=False, default="1.0"
    )

    # Deterministic summary of the weakest signals, built from the score
    # breakdown rather than generated by the AI.
    summary: Mapped[str | None] = mapped_column(Text)
    # Stored per row so the heuristic caveat cannot be separated from the number.
    disclaimer: Mapped[str] = mapped_column(
        Text, nullable=False, default=HEURISTIC_DISCLAIMER
    )

    # --- headline signal flags, denormalised for fast dashboard reads --------
    has_faq_content: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False
    )
    has_structured_data: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False
    )
    has_clear_entity_info: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False
    )
    has_freshness_signals: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False
    )

    scan: Mapped[WebsiteScan] = relationship(back_populates="ai_visibility_report")
    category_scores: Mapped[list[AiVisibilityCategoryScore]] = relationship(
        back_populates="report",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    __table_args__ = (
        CheckConstraint(
            "overall_score >= 0 AND overall_score <= 100",
            name="valid_ai_visibility_score",
        ),
    )

    @property
    def score_grade(self) -> ScoreGrade:
        return ScoreGrade.from_score(self.overall_score)


class AiVisibilityCategoryScore(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """One AI-visibility signal group within a report."""

    __tablename__ = "ai_visibility_scores"

    report_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("ai_visibility_reports.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    category: Mapped[str] = mapped_column(String(30), nullable=False)
    points_earned: Mapped[float] = mapped_column(Float, nullable=False)
    points_available: Mapped[float] = mapped_column(Float, nullable=False)
    normalized_score: Mapped[float] = mapped_column(Float, nullable=False)
    weight: Mapped[float] = mapped_column(Float, nullable=False)

    # Why this category scored as it did, in user-facing language. Every
    # AI-visibility score must be explainable (spec section 7).
    explanation: Mapped[str | None] = mapped_column(Text)
    # Per-signal detail: {"faq_present": {"passed": false, "points": 0, "max": 6}}
    signal_results: Mapped[dict[str, Any]] = mapped_column(
        JSONColumn, nullable=False, default=dict
    )

    report: Mapped[AiVisibilityReport] = relationship(back_populates="category_scores")

    __table_args__ = (
        UniqueConstraint("report_id", "category", name="unique_ai_category_per_report"),
        CheckConstraint(
            "normalized_score >= 0 AND normalized_score <= 100",
            name="valid_ai_category_score",
        ),
        CheckConstraint("points_available > 0", name="positive_ai_points_available"),
    )
